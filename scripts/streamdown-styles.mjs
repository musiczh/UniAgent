import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const result = spawnSync('pnpm', ['exec', 'tailwindcss', '-i', 'src/renderer/streamdown.input.css', '--minify'], {
  encoding: 'utf8', maxBuffer: 2 * 1024 * 1024,
})
if (result.status !== 0) throw new Error(result.stderr || result.error?.message || 'Streamdown style generation failed')
if (!result.stdout.includes(':root,:host')) throw new Error('Tailwind theme root is missing')
const css = result.stdout.replaceAll(':root,:host', ':scope')
const output = `/* Generated by pnpm run build:markdown-styles. Scoped to Markdown; no global preflight. */\n@scope (.agent-md) {\n${css}\n}\n`
const file = resolve('src/renderer/streamdown.css')
let previous = ''
try { previous = readFileSync(file, 'utf8') } catch { /* First build. */ }
if (previous !== output) writeFileSync(file, output)
console.log('Streamdown Markdown styles generated')
