import assert from 'node:assert/strict'
import { modelQuotaRequestFor } from '../src/main/model-sources/quota'

const request = (preset: any, base: string, context = {}) => modelQuotaRequestFor(preset, base, 'fixture-key', context, new Date('2026-11-18T03:04:05Z'))
for (const [id, base, url] of [
  ['minimax-cn', 'https://api.minimaxi.com/v1', 'https://api.minimaxi.com/v1/api/openplatform/coding_plan/remains'],
  ['minimax', 'https://api.minimax.io/v1', 'https://api.minimax.io/v1/api/openplatform/coding_plan/remains'],
  ['siliconflow-cn', 'https://api.siliconflow.cn/v1', 'https://api.siliconflow.cn/v1/user/info'],
  ['openrouter', 'https://openrouter.ai/api/v1', 'https://openrouter.ai/api/v1/credits'],
  ['stepfun', 'https://api.stepfun.com/v1', 'https://api.stepfun.com/v1/accounts'],
  ['novita', 'https://api.novita.ai/v3/openai', 'https://api.novita.ai/v3/user/balance'],
  ['kimi-code-global', 'https://api.kimi.ai/coding/v1', 'https://api.kimi.ai/coding/v1/usages']
]) { const value = request(id, base)!; assert.equal(value.url, url); assert.equal(value.authorization, 'Bearer fixture-key') }
assert.equal(request('openrouter', 'https://proxy.example/v1'), null)
assert.equal(request('deepseek', 'https://api.deepseek.com.evil.test'), null)
assert.equal(request('sub2api', 'https://proxy.example/v1'), null, 'generic templates require explicit selection')
assert.equal(request('sub2api', 'https://proxy.example/team/anthropic', { query: { template: 'sub2api' } })?.url, 'https://proxy.example/team/v1/usage')
assert.throws(() => request('new-api', 'https://proxy.example/v1', { query: { template: 'new-api', userId: '123' } }), /令牌/)
const newApi = request('new-api', 'https://proxy.example/v1', { query: { template: 'new-api', userId: '123' }, credentials: { accessToken: 'fixture-token' } })!
assert.equal(newApi.url, 'https://proxy.example/api/user/self')
assert.equal(newApi.authorization, 'Bearer fixture-token')
assert.equal(newApi.headers?.['New-Api-User'], '123')
assert.throws(() => request('ark-coding-plan', 'https://ark.cn-beijing.volces.com/api/coding'), /AK.*SK/)
const context = { credentials: { accessKeyId: 'fixture-ak', secretAccessKey: 'fixture-sk' } }
const coding = request('ark-coding-plan', 'https://ark.cn-beijing.volces.com/api/coding', context)!
const agent = request('ark-agent-plan', 'https://ark.cn-beijing.volces.com/api/plan', context)!
assert.equal(coding.method, 'POST')
assert.equal(coding.url, 'https://open.volcengineapi.com/?Action=GetCodingPlanUsage&Region=cn-beijing&Version=2024-01-01')
assert.match(agent.url, /Action=GetAFPUsage/)
assert.equal(coding.headers?.['X-Date'], '20261118T030405Z')
assert.equal(coding.headers?.['X-Content-Sha256'], 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855')
assert.match(coding.authorization, /^HMAC-SHA256 Credential=fixture-ak\/20261118\/cn-beijing\/ark\/request, SignedHeaders=host;x-content-sha256;x-date, Signature=[a-f0-9]{64}$/)
// Generated by volcengine/volc-sdk-nodejs src/base/sign.ts @ 6e8d98cfca31b83f2f920570882785b3283b57ce.
assert.equal(coding.authorization.split('Signature=')[1], 'ac0616c0895236bc023a26b4a0ae06c02f6a03d6b20d613d64cb999190e9bf1e')
assert.notEqual(coding.authorization, agent.authorization)
assert.ok(!JSON.stringify(coding).includes('fixture-sk'))
console.log('model-source-quota-requests: destinations, credentials and Ark signed request contracts passed')
