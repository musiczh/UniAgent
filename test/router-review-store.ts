import assert from 'node:assert/strict'
import { mkdtemp, readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { randomUUID } from 'node:crypto'
import { RouterDatabase } from '../src/main/router/database'
import { DEFAULT_ROUTER_CONFIG, type RouterRequest } from '../src/shared/router'
import { parseRouterFeedback, sanitizeRouterReview } from '../src/shared/routerReview'

const root = await mkdtemp(join(tmpdir(), 'ua-router-review-')), path = join(root, 'router.sqlite')
let database = new RouterDatabase(path)
const request = (text: string): RouterRequest => { const value = database.register({ requestId: randomUUID(), prompt: text }, DEFAULT_ROUTER_CONFIG); return database.update(value.requestId, value.version, { state: 'bound', delivery: 'accepted', targetId: 'original', targetTitle: '原任务', decision: { action: 'reuse_task', taskId: 'original', reason: '同一目标' } }) }
try {
  const original = request('继续修复图片漏显'), originalVersion = database.request(original.requestId)!.version
  const attempt = await database.reviewBegin(original, 'router-fixed', 'Router 系统规则', [], 'test-version')
  const context = { objects: [{ id: 'original', title: '原任务', summary: '继续同一问题' }], memories: [], headers: { authorization: 'Bearer fixture-token' }, text: 'API_KEY=fixture-secret' }
  await database.reviewStep(original.requestId, 'query', context); context.objects[0].title = '后来改名'
  await database.reviewFinish(original, [{ sessionId: 'router-fixed', seq: 1, ts: 1, type: 'reasoning', payload: { text: '读取候选后命中原任务' } }])
  assert.equal((await database.reviewPrompts()).length, 1)
  const detail = await database.reviewDetail(original.requestId, attempt, true)
  assert.equal((detail.trace!.steps[0].data as any).objects[0].title, '原任务', 'snapshot survives subsequent candidate mutation')
  assert.equal(detail.trace!.reasoning, 'provided')
  assert.equal(detail.trace!.assembledContext, 'not-provided')
  const persisted = await readFile(join(root, 'reviews', original.requestId, `attempt-${attempt}.json`), 'utf8')
  assert.ok(!persisted.includes('fixture-secret') && !persisted.includes('fixture-token'))
  assert.ok(!('headers' in (detail.trace!.steps[0].data as any)))
  let saved = await database.reviewSave({ requestId: original.requestId, attemptId: attempt, expectedRevision: 0, matches: false })
  assert.equal(saved.feedback!.matches, false); assert.equal(saved.feedback!.expected, undefined)
  assert.equal(database.request(original.requestId)!.version, originalVersion, 'feedback never mutates routing state or version')
  assert.equal((await database.reviewPrompts()).length, 0)
  await assert.rejects(database.reviewSave({ requestId: original.requestId, attemptId: attempt, expectedRevision: 0, matches: true }), /反馈已变化/)
  for (const expected of [{ kind: 'create_task' as const }, { kind: 'reuse_task' as const, projectId: 'space' }, { kind: 'create_requirement' as const }]) {
    saved = await database.reviewSave({ requestId: original.requestId, attemptId: attempt, expectedRevision: saved.revision, matches: false, expected })
    assert.equal(saved.feedback!.expected!.kind, expected.kind, 'partial optional expected target is accepted')
  }
  const legacy = request('没有旧快照的历史任务')
  const legacyDetail = await database.reviewDetail(legacy.requestId)
  assert.equal(legacyDetail.traceAvailable, false); assert.equal(legacyDetail.trace, undefined)
  await database.reviewLinkLegacy(legacy.requestId, 'router-fixed', [
    { sessionId: 'router-fixed', seq: 0, ts: 1, type: 'user_message', payload: { text: 'requestId=' + legacy.requestId } },
    { sessionId: 'router-fixed', seq: 1, ts: 1, type: 'reasoning', payload: { text: '已有历史分析' } },
    { sessionId: 'router-fixed', seq: 2, ts: 1, type: 'tool_call', payload: { name: 'router_assign_task', input: { requestId: legacy.requestId } } },
    { sessionId: 'router-fixed', seq: 3, ts: 1, type: 'turn_completed', payload: {} },
    { sessionId: 'router-fixed', seq: 4, ts: 1, type: 'user_message', payload: { text: '另一条输入' } },
    { sessionId: 'router-fixed', seq: 5, ts: 1, type: 'agent_message', payload: { text: '其他请求的结果' } },
  ])
  const legacyLogs = await database.reviewDetail(legacy.requestId, undefined, true)
  assert.equal(legacyLogs.traceAvailable, false, 'legacy events must not pretend a captured context exists')
  assert.equal(legacyLogs.diagnostics!.reasoning, 'provided')
  assert.match(legacyLogs.diagnostics!.sections[0].text, /not-captured/)
  assert.ok(!legacyLogs.diagnostics!.sections[0].text.includes('其他请求的结果'))
  await database.reviewSave({ requestId: legacy.requestId, expectedRevision: 0, matches: true })
  const legacyExport = await database.reviewExport(legacy.requestId)
  const legacyIndex = JSON.parse(await readFile(join(legacyExport.directory, 'index.json'), 'utf8'))
  const legacyRecord = JSON.parse(await readFile(join(legacyExport.directory, legacyIndex.records[0].record), 'utf8'))
  assert.equal(legacyRecord.logAvailability, 'legacy-events-only')
  assert.equal(legacyIndex.records[0].traces.length, 1)
  const dismissed = request('只忽略不评价')
  const ignoredAttempt = await database.reviewBegin(dismissed, 'router-fixed', '规则', [], 'test')
  await database.reviewFinish(dismissed, []); await database.reviewDismiss(dismissed.requestId, ignoredAttempt)
  assert.equal((await database.reviewDetail(dismissed.requestId)).feedback, undefined)
  const unfinished = request('恢复中的路由'), unfinishedAttempt = await database.reviewBegin(unfinished, 'router-fixed', '规则', [], 'test')
  await assert.rejects(database.reviewSave({ requestId: unfinished.requestId, attemptId: unfinishedAttempt, expectedRevision: 0, matches: false }), /已结束/)
  await database.reviewRecover()
  assert.equal((await database.reviewPrompts()).length, 0, 'startup does not replay feedback popovers')
  const second = await database.reviewBegin(original, 'router-fixed', '新版规则', [], 'test'); await database.reviewFinish(original, [])
  assert.equal((await database.reviewDetail(original.requestId)).feedback, undefined, 'new attempt has independent feedback')
  assert.equal((await database.reviewDetail(original.requestId, attempt)).feedbackHistory.length, 4)
  await database.reviewSave({ requestId: original.requestId, attemptId: second, expectedRevision: saved.revision, matches: true })
  const page = await database.reviewList({ filter: 'good', limit: 1 })
  assert.equal(page.total, 2); assert.equal(page.rows.length, 1)
  assert.equal((await database.reviewList({ search: '图片' })).total, 1)
  await assert.rejects(database.reviewList({ offset: -1 }), /格式无效/)
  assert.throws(() => parseRouterFeedback({ requestId: original.requestId, expectedRevision: 0 }), /请选择/)
  assert.throws(() => parseRouterFeedback({ requestId: '../escape', expectedRevision: 0, matches: false }), /request_id/)
  assert.throws(() => parseRouterFeedback({ requestId: original.requestId, expectedRevision: 0, matches: false, expected: { kind: 'create_task', scope: 'space', requirementId: 'req' } }), /归属类型/)
  assert.ok(!sanitizeRouterReview('原始参数：{"apiKey":"fixture-secret"}').includes('fixture-secret'))
  const exported = await database.reviewExport(original.requestId)
  assert.equal(exported.count, 1); assert.ok(exported.prompt.includes(exported.directory) && exported.prompt.includes('README.md'))
  const index = JSON.parse(await readFile(join(exported.directory, 'index.json'), 'utf8'))
  assert.equal(index.records[0].traces.length, 2)
  const record = JSON.parse(await readFile(join(exported.directory, index.records[0].record), 'utf8'))
  assert.equal(record.feedbacks.length, 5); assert.equal(record.request.prompt, original.prompt)
  database.close(); database = new RouterDatabase(path)
  assert.equal((await database.reviewDetail(original.requestId)).feedback!.matches, true, 'feedback survives restart')
  const plan = await database.reviewDeletion([original.requestId])
  assert.equal(plan.items.length, 1)
  const receipt = database.request(original.requestId)
  assert.deepEqual(await database.reviewDelete(plan.items), { deletedIds: [original.requestId], skippedIds: [], failures: [] })
  assert.deepEqual(database.request(original.requestId), receipt, 'deleting reviews preserves the execution receipt and version')
  assert.deepEqual(database.register({ requestId: original.requestId, prompt: original.prompt }, DEFAULT_ROUTER_CONFIG), receipt, 'deleting reviews preserves input deduplication')
  assert.deepEqual(await readdir(join(root, 'reviews', original.requestId)), ['review.json'], 'all attempt logs are removed')
  assert.ok(!(await readFile(join(root, 'reviews', original.requestId, 'review.json'), 'utf8')).includes(original.prompt), 'tombstone contains no feedback or input')
  await assert.rejects(database.reviewDetail(original.requestId), /该路由记录已删除/)
  await assert.rejects(database.reviewSave({ requestId: original.requestId, expectedRevision: 0, matches: false }), /该路由记录已删除/)
  await assert.rejects(database.reviewExport(original.requestId), /该路由记录已删除/)
  assert.equal(await database.reviewBegin(original, 'router-fixed', '规则', [], 'test'), undefined, 'deleted requests never recreate diagnostics')
  await database.reviewStep(original.requestId, 'late_query', {}); await database.reviewFinish(original, [])
  await database.reviewLinkLegacy(original.requestId, 'router-fixed', []); await database.reviewDismiss(original.requestId, attempt)
  assert.ok(!(await database.reviewPrompts()).some(row => row.requestId === original.requestId))
  assert.deepEqual(await database.reviewDelete(plan.items), { deletedIds: [original.requestId], skippedIds: [], failures: [] }, 'delete retries are idempotent')
  assert.equal(JSON.parse(await readFile(join(exported.directory, 'index.json'), 'utf8')).records.length, 1, 'previous export snapshots remain intact')
  const newExport = await database.reviewExport()
  assert.ok(!JSON.parse(await readFile(join(newExport.directory, 'index.json'), 'utf8')).records.some((row: any) => row.requestId === original.requestId))
  const protectedIds: string[] = []
  for (const state of ['queued', 'routing', 'committing'] as const) { const value = request(state); database.update(value.requestId, value.version, { state }); protectedIds.push(value.requestId) }
  const inflight = request('日志尚未结束'); await database.reviewBegin(inflight, 'router-fixed', '规则', [], 'test'); protectedIds.push(inflight.requestId)
  assert.equal((await database.reviewDeletion(protectedIds)).protectedCount, 4)
  assert.deepEqual((await database.reviewDeletion(protectedIds)).items, [])
  assert.ok((await database.reviewList()).rows.filter(row => protectedIds.includes(row.request.requestId)).every(row => row.deletable === false))
  const stale = request('确认期间状态变化'), stalePlan = await database.reviewDeletion([stale.requestId])
  database.update(stale.requestId, stale.version, { state: 'routing' })
  assert.deepEqual((await database.reviewDelete(stalePlan.items)).skippedIds, [stale.requestId])
  const changed = request('确认期间反馈变化'), changedPlan = await database.reviewDeletion([changed.requestId])
  await database.reviewSave({ requestId: changed.requestId, expectedRevision: 0, matches: false })
  assert.deepEqual((await database.reviewDelete(changedPlan.items)).skippedIds, [changed.requestId])
  assert.equal((await database.reviewDetail(changed.requestId)).feedback!.matches, false)
  for (let index = 0; index < 103; index++) request('分页历史 ' + index)
  const clearPlan = await database.reviewDeletion(), arriving = request('确认后到达')
  const clear = await database.reviewDelete(clearPlan.items)
  assert.equal(clear.deletedIds.length, clearPlan.items.length, 'clear covers every page without the regular request limit')
  assert.deepEqual(clear.failures, [])
  assert.ok((await database.reviewList()).rows.some(row => row.request.requestId === arriving.requestId), 'new arrivals survive an earlier clear snapshot')
  assert.equal((await database.reviewList()).counts.all, 6, 'all counts exclude deleted rows and preserve protected and arriving requests')
  database.close(); database = new RouterDatabase(path); await database.reviewRecover()
  assert.equal((await database.reviewList()).counts.all, 6, 'deleted records do not return on restart')
  await writeFile(join(root, 'reviews', original.requestId, 'interrupted-cleanup.json'), 'interrupted cleanup')
  await database.reviewRecover()
  assert.deepEqual(await readdir(join(root, 'reviews', original.requestId)), ['review.json'], 'restart completes log cleanup after a persisted deletion marker')
  await assert.rejects(database.reviewDeletion(['../escape']), /request_id/)
  await assert.rejects(database.reviewDelete([{ requestId: arriving.requestId, requestVersion: -1, reviewRevision: 0 }]), /格式无效/)
  await assert.rejects(database.reviewDelete([clearPlan.items[0], clearPlan.items[0]]), /格式无效/)
  const broken = request('损坏记录不得被覆盖'); await mkdir(join(root, 'reviews', broken.requestId), { recursive: true }); await writeFile(join(root, 'reviews', broken.requestId, 'review.json'), '{')
  await assert.rejects(database.reviewSave({ requestId: broken.requestId, expectedRevision: 0, matches: false }))
  assert.equal(await readFile(join(root, 'reviews', broken.requestId, 'review.json'), 'utf8'), '{')
  const partial = await database.reviewDelete([{ requestId: broken.requestId, requestVersion: broken.version, reviewRevision: 0 }, ...(await database.reviewDeletion([arriving.requestId])).items])
  assert.deepEqual(partial.deletedIds, [arriving.requestId]); assert.equal(partial.failures[0].requestId, broken.requestId)
  assert.equal(await readFile(join(root, 'reviews', broken.requestId, 'review.json'), 'utf8'), '{', 'failed deletion preserves unreadable data')
  console.log('PASS Router reviews: immutable snapshots, optional feedback, version conflict, attempts, dismissal, restart, redaction, pagination and local export')
} finally { database.close() }
